const { chromium } = require('C:/Users/PC/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--allow-file-access-from-files'] });
  const page = await browser.newPage({ viewport: { width: 960, height: 820 }, deviceScaleFactor: 1 });
  page.on('pageerror', err => console.log('PAGE ERROR:', err.message));
  page.on('console', message => { if (message.type() === 'error') console.log('CONSOLE ERROR:', message.text()); });
  await page.goto('file:///' + path.resolve(__dirname, 'render-harness.html').replace(/\\/g, '/'));
  await page.waitForFunction(() => window.orangeScene && orangeScene.ready);
  await page.evaluate(() => { orangeScene.setPaused(true); orangeScene.reset(); });
  await page.screenshot({ path: path.join(__dirname, 'sculpture-fallback.png'), omitBackground: false });
  console.log('hero rendered');
  await page.setViewportSize({ width: 1000, height: 800 });
  await page.evaluate(() => { document.body.style.background = '#ebece8'; orangeScene.render(); });
  await page.screenshot({ path: path.join(__dirname, 'project-form.png') });
  await page.addScriptTag({ path: path.join(__dirname, 'project-renderer.js') });
  const motion = await page.evaluate(() => renderProject('motion'));
  fs.writeFileSync(path.join(__dirname, 'project-motion.png'), Buffer.from(motion.split(',')[1], 'base64'));
  await page.reload();
  await page.addScriptTag({ path: path.join(__dirname, 'project-renderer.js') });
  const scan = await page.evaluate(() => renderProject('scan'));
  fs.writeFileSync(path.join(__dirname, 'project-scan.png'), Buffer.from(scan.split(',')[1], 'base64'));
  console.log('projects rendered');
  await browser.close();
})();
